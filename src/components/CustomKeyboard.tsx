/**
|--------------------------------------------------
| Npm imports
|--------------------------------------------------
*/
import React from 'react';
import { Svg, Path } from 'react-native-svg';
import { View, TouchableOpacity } from 'react-native';

/**
|--------------------------------------------------
| Custom imports
|--------------------------------------------------
*/
import MPText from './MPText';

/**
|--------------------------------------------------
| Interface
|--------------------------------------------------
*/
interface Props {
	length?: number;
	onComplete?: (pin: string) => void;
}

export default function CustomKeyboard({ length = 4, onComplete }: Props) {
	/**
    |--------------------------------------------------
    | States
    |--------------------------------------------------
    */
	const [pin, setPin] = React.useState<string[]>([]);

	/**
    |--------------------------------------------------
    | Handles pressing the keys
    |--------------------------------------------------
    */
	const handlePress = (num: string) => {
		/**
        |--------------------------------------------------
        | Checks if the length of the input is maxed out
        |--------------------------------------------------
        */
		if (pin.length < length) {
			const newPin = [...pin, num];
			setPin(newPin);

			/**
            |--------------------------------------------------
            | Runs the onComplete function if the input lenght
            | is maxed out
            |--------------------------------------------------
            */
			if (newPin.length === length && onComplete) {
				onComplete(newPin.join(''));
			}
		}
	};

	/**
    |--------------------------------------------------
    | Handles deleting an input
    |--------------------------------------------------
    */
	const handleDelete = () => {
		setPin(pin.slice(0, -1));
	};

	/**
    |--------------------------------------------------
    | Rendered View
    |--------------------------------------------------
    */
	return (
		<View className="max-w-[260px] w-full self-center">
			{/**
            |--------------------------------------------------
            | PIN Boxes
            |--------------------------------------------------
            */}
			<View className="flex-row justify-center mb-12">
				{Array.from({ length }).map((_, index) => (
					<View
						key={index}
						className={`w-12 h-12 mx-2 rounded-xl flex bg-[#F7F7F7] items-center justify-center`}
					>
						{pin[index] && <View className="w-3 h-3 rounded-full bg-green-500" />}
					</View>
				))}
			</View>

			{/**
            |--------------------------------------------------
            | Keypad
            |--------------------------------------------------
            */}
			<View>
				{[
					['1', '2', '3'],
					['4', '5', '6'],
					['7', '8', '9'],
					['', '0', '⌫'],
				].map((row, rowIndex) => (
					<View key={rowIndex} className="flex-row my-2 justify-between">
						{row.map((key, keyIndex) => (
							<TouchableOpacity
								key={keyIndex}
								onPress={() => {
									if (key === '⌫') handleDelete();
									else if (key) handlePress(key);
								}}
								className={`w-16 h-16 mb-[7%] rounded-full flex items-center justify-center ${key ? 'bg-gray-100' : 'bg-transparent'}`}
							>
								<MPText weight="medium" style={{ lineHeight: 30, fontSize: 24 }} className="text-2xl">
									{key === '⌫' ? (
										<Svg width="24" height="24" viewBox="0 0 24 24" fill="none">
											<Path
												d="M18.7502 4C19.5803 3.99995 20.379 4.31755 20.9824 4.88767C21.5858 5.45779 21.9482 6.23719 21.9952 7.066L22.0002 7.25V16.75C22.0002 17.5801 21.6826 18.3788 21.1125 18.9822C20.5424 19.5856 19.763 19.948 18.9342 19.995L18.7502 20H10.2492C9.48703 20.0003 8.74904 19.7327 8.16418 19.244L8.00918 19.105L3.01418 14.355C2.38972 13.7611 2.0267 12.9435 2.00494 12.082C1.98319 11.2205 2.30449 10.3856 2.89818 9.761L3.01418 9.645L8.00918 4.895C8.56146 4.36993 9.28068 4.05562 10.0412 4.007L10.2502 4H18.7502ZM11.4462 8.397C11.3017 8.28948 11.1233 8.23755 10.9437 8.25069C10.7641 8.26384 10.5952 8.3412 10.4679 8.46862C10.3406 8.59603 10.2634 8.76501 10.2504 8.94465C10.2374 9.12429 10.2895 9.30261 10.3972 9.447L10.4702 9.53L12.9402 12L10.4702 14.47L10.3972 14.554C10.2897 14.6985 10.2377 14.8769 10.2509 15.0565C10.264 15.2361 10.3414 15.405 10.4688 15.5323C10.5962 15.6596 10.7652 15.7368 10.9448 15.7498C11.1245 15.7628 11.3028 15.7107 11.4472 15.603L11.5302 15.53L14.0002 13.061L16.4702 15.531L16.5542 15.603C16.6987 15.7105 16.877 15.7625 17.0567 15.7493C17.2363 15.7362 17.4052 15.6588 17.5325 15.5314C17.6598 15.404 17.737 15.235 17.75 15.0554C17.7629 14.8757 17.7108 14.6974 17.6032 14.553L17.5302 14.47L15.0612 12L17.5312 9.53L17.6032 9.446C17.7107 9.3015 17.7626 9.12314 17.7495 8.94351C17.7363 8.76388 17.659 8.59498 17.5316 8.46768C17.4041 8.34039 17.2352 8.26319 17.0555 8.25022C16.8759 8.23724 16.6976 8.28934 16.5532 8.397L16.4702 8.47L14.0002 10.939L11.5302 8.469L11.4462 8.397Z"
												fill="#0B081B"
											/>
										</Svg>
									) : (
										key
									)}
								</MPText>
							</TouchableOpacity>
						))}
					</View>
				))}
			</View>
		</View>
	);
}
